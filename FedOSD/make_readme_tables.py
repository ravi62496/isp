"""Turn the evaluator's script-generated CSV/JSON outputs into README-ready markdown tables.
Reads only files written by evaluate_confirmation.py (no recomputation, no hand-typed numbers).

Usage: python make_readme_tables.py [results_confirm_dir] [out.md]
"""
import csv, glob, json, os, sys

D = sys.argv[1] if len(sys.argv) > 1 else 'results_confirm'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'README_confirmation_tables.md'

def read(pattern):
    files = sorted(glob.glob(os.path.join(D, pattern)))
    # The evaluator also writes *_exploratory.csv variants; the confirmatory tables are the others.
    non_expl = [f for f in files if not f.endswith('_exploratory.csv')]
    if len(files) > 1 and len(non_expl) == 1:
        files = non_expl
    if len(files) != 1:
        raise SystemExit('Expected exactly one file for %s in %s, found %s' % (pattern, D, files))
    with open(files[0], newline='', encoding='utf-8') as f:
        return files[0], list(csv.DictReader(f))

def fnum(x, nd=2, sign=False):
    v = float(x)
    return ('%+.*f' % (nd, v)) if sign else ('%.*f' % (nd, v))

def family_table(rows):
    a, b = rows[0]['arm_test'], rows[0]['arm_comp']
    out = ['| Metric | Method (%s) | Comparator (%s) | Diff (95%% CI, t) | p (Holm) | Label |' % (a, b),
           '|---|---|---|---|---|---|']
    for r in rows:
        out.append('| %s | %s | %s | %s [%s, %s] | %s | %s |' % (
            r['metric_name'], fnum(r['test_mean']), fnum(r['comp_mean']),
            fnum(r['diff_est'], 2, True), fnum(r['ci95_t_low'], 2, True), fnum(r['ci95_t_high'], 2, True),
            fnum(r['p_holm'], 4), r['label']))
    return '\n'.join(out)

parts = ['# Confirmation results (generated by make_readme_tables.py from evaluator output)\n']

_, summ = read('table_summary.csv')
parts += ['## Strength matching and sample size\n',
          '| Family | n | Strength matched | Displacement ratio | abs ASR diff (pt) |', '|---|---|---|---|---|']
for r in summ:
    parts.append('| %s | %s | %s | %s | %s |' % (r['family'], r['n'], r['strength_matched'],
                                                  fnum(r['disp_ratio'], 4), fnum(r['asr_diff'], 2)))
parts.append('')

for title, pat in (('F1 (confirmatory): A3 vs A2 at round 100', 'table_F1_*.csv'),
                   ('F2 (secondary, pre-registered): A3 vs A2 at round 200', 'table_F2_*.csv'),
                   ('Sensitivity control (exploratory): A1 vs A2 at round 100', 'table_Sensitivity_*.csv')):
    f, rows = read(pat)
    parts += ['## ' + title + '\n', family_table(rows), '', 'Source file: `%s`\n' % os.path.basename(f)]

sj = sorted(glob.glob(os.path.join(D, 'eval_summary_*.json')))
if len(sj) == 1:
    o = json.load(open(sj[0], encoding='utf-8')).get('confirmatory_outcome', {})
    parts += ['## Pre-registered outcome\n', '**%s** - %s\n' % (o.get('outcome'), o.get('description'))]
    parts.append('Source file: `%s`\n' % os.path.basename(sj[0]))

open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(parts))
print('Wrote', OUT)